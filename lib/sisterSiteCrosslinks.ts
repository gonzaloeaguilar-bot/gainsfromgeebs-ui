export function getSisterSiteCrosslink(sourcePath: string): SisterSiteCrosslink | null {
  const crosslink = SISTER_SITE_CROSSLINKS[sourcePath];
  if (!crosslink) return null;

  // Preserve a meaningful, editorial crosslink while making its actual referral
  // contribution observable in Titan's GA4 property. Campaign values are stable
  // across releases; `utm_content` identifies the source page without creating a
  // separate destination URL for indexing purposes.
  const target = new URL(crosslink.targetUrl);
  target.searchParams.set("utm_source", "gainsfromgeebs");
  target.searchParams.set("utm_medium", "referral");
  target.searchParams.set("utm_campaign", "geebs_titanforge_contextual_link");
  target.searchParams.set("utm_content", sourcePath.replace(/^\//, ""));

  return { ...crosslink, targetUrl: target.toString() };
}
