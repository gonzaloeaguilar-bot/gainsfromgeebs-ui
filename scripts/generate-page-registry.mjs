/**
 * Generates data/pages/index.ts from the modules in data/pages/.
 *
 * WHY: index.ts was the last file every page had to share. Three separate
 * attempts to merge it during landing went wrong — one overwrote a sibling's
 * registration and silently de-listed /science/boron, one produced
 * `vsTrainwell,,` plus a duplicated symbol, and one no-oped and left
 * /science/omega-3-and-hormones unregistered. Regex-editing structured source
 * is the wrong tool.
 *
 * Generating it removes the shared file from the merge surface completely: a
 * page contributes exactly one module, and this script derives the index. Two
 * pages built in parallel can no longer collide.
 *
 * data/pages/index.ts is imported by a client component, so it cannot read the
 * filesystem at runtime — hence generation at build time rather than a glob.
 *
 * Run: npm run registry:generate  (wired into prebuild, ahead of blog:validate)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "data/pages";
const OUT = join(DIR, "index.ts");

const camel = (slug) =>
  slug.replace(/[-_](\w)/g, (_, c) => c.toUpperCase()).replace(/^\w/, (c) => c.toLowerCase());

const modules = readdirSync(DIR)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const body = `// GENERATED by scripts/generate-page-registry.mjs — do not edit by hand.
// Add a page by creating data/pages/<slug>.ts; this index is derived from the
// directory so parallel page branches never collide on a shared file.
import type { PageRegistration } from "@/lib/pageRegistry";
${modules.map((m) => `import ${camel(m)} from "./${m}";`).join("\n")}

export const registeredPages: PageRegistration[] = [
${modules.map((m) => `  ${camel(m)},`).join("\n")}
];

export default registeredPages;
`;

const prev = (() => { try { return readFileSync(OUT, "utf8"); } catch { return ""; } })();
if (prev !== body) {
  writeFileSync(OUT, body);
  console.log(`✓ Page registry regenerated — ${modules.length} pages.`);
} else {
  console.log(`✓ Page registry up to date — ${modules.length} pages.`);
}

// Note: the registry is regenerated on every prebuild, so a page module added by
// a parallel branch is picked up automatically at build time rather than being
// merged into a shared index by hand.
